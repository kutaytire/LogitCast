"""OpenForesight as multiple choice under a fixed option protocol, the same for every split and every model.

The options of a question are its true answer and N_DISTRACTORS distractors built by these rules, every model
call made by gpt-oss-120b, a family distinct from the systems compared (OpenForecaster-8B is Qwen3-8B after RL,
JEV is Qwen3.5):
  1. Real answers. The candidates are the true answers of the most similar other questions with the same
     normalised answer type (TF-IDF over question text, as pipeline/build_openforesight.py), most similar first, then
     those of the most similar questions of any type, up to MAX_CANDIDATES;
     training questions draw from the training pool only, other splits from the training pool and their own.
     Truth and distractors are then outcomes of the same kind of source. Candidates generated by a model are not
     used: a model tuned on such sets learns to tell its guesses from the real outcome, so with the question and
     context hidden it found the truth 41-60% of the time (results/optonly, chance 20%), while sets of real
     answers stayed at chance.
     Evaluation splits (test, futureSim2026Q2) keep every question: where fewer than N_DISTRACTORS + 2 real
     answers fit, the model's blind candidates follow them (it reads only what was known at the question start
     date, its chat template's current date set to that date, and lists N_GENERATED answers a well-informed
     forecaster would consider, most likely first), checked by rules 2-3 like the real ones. No model is tuned
     on such sets: training splits (train, val) drop those questions. Rows count their generated distractors.
  2. Kind and form (gpt-oss). Each candidate is checked for the kind of answer the question asks for and the accepted
     answer format, not for its likelihood; misfits are dropped. Candidates are checked N_CANDIDATES at a time,
     most similar first, until N_DISTRACTORS + 2 fit, so that no question is dropped for want of distractors.
  3. Exactly one correct. Candidates that restate the true answer (string containment, then the authors' judge
     prompt, answer_judge.judge_prompt) or repeat an earlier candidate are dropped.
  4. Balanced order, one style. The option set is the first N_DISTRACTORS survivors, shuffled with a seed per
     question, with the truth inserted at position (k mod number of options) for the split's k-th kept question,
     so every position holds the truth equally often. The set is rewritten into one consistent style without
     changing what any option refers to, so that form cannot single out the truth. The rewrite does not know which option is true; it is kept only if the judge finds the rewritten
     truth equivalent to the original and no rewritten distractor overlaps it.
  5. Option-only probe (as hypothesis-only baselines). The model sees the options alone, without the question,
     and gives a probability per option from its next-token distribution over the letters. This checks the set
     as a whole: its accuracy must be within 5 points of chance (1 / number of options). It selects nothing per
     question, since choosing each question's options by the probe biases the probe's own statistics.
Training splits drop questions with fewer than N_DISTRACTORS survivors. Evaluation splits keep every question
with at least one: a question whose answers form a small closed set (a chamber of Congress, a cricket format)
gets as many options as it has distinct valid answers.

Splits: train and val (the questions of openforesight_choice_half.parquet, JEV's training set) and
futureSim2026Q2 (FutureSim 2026-Q2) keep the columns of openforesight_choice.parquet and are written to
data/openforesight_options.parquet; test (the authors' 302-question test set, from the raw data) is written to
data/openforesight_options_test.parquet for baselines/baseline_openforecaster_options.py, and aljazeera2026Q3 (302 questions
resolving Jul-Sep 2026, added to the dataset on 2026-11-02, also from the raw data) to
data/openforesight_options_q3.parquet. Rules 1-2 are cached in
data/openforesight_options_candidates_SPLIT.parquet. Rows keep the candidates and the probe's probability on the
truth for auditing; the summary prints the protocol's diagnostics. Run in the vllm venv on a whole GPU.
"""
import argparse
import glob
import json
import os
import re
from datetime import date

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from transformers import AutoTokenizer
from vllm import LLM, SamplingParams

from pipeline.answer_judge import judge_prompt
from pipeline.build_openforesight import RAW, SPLITS, distractors, load, norm, state_text
from pipeline.candidates import ROOT

MODEL = "openai/gpt-oss-120b"
N_CANDIDATES = 30
MAX_CANDIDATES = 600
N_GENERATED = 10
FALLBACK = ("test", "futureSim2026Q2", "aljazeera2026Q3")
STANDALONE = {"test": "data/openforesight_options_test.parquet",  # built from the raw fields, in a file of its own
              "aljazeera2026Q3": "data/openforesight_options_q3.parquet"}
N_DISTRACTORS = 4
LETTERS = "ABCDE"
BASE = os.path.join(ROOT, "data/openforesight_choice_half.parquet")
RAW_NAME = {"train": "train", "val": "validation", "futureSim2026Q2": "futureSim2026Q2", "test": "test",
            "aljazeera2026Q3": "aljazeera2026Q3"}


def out_path(split):
    return os.path.join(ROOT, STANDALONE.get(split, "data/openforesight_options.parquet"))


def cand_path(split):
    return os.path.join(ROOT, f"data/openforesight_options_candidates_{split}.parquet")


def questions(split):
    """The split's questions: raw fields plus, except for test, the rows of openforesight_choice_half.parquet. Test
    builds the same JEV columns from the raw fields, as pipeline/build_openforesight.py does for the other splits."""
    name = RAW_NAME[split]
    raw = load(name).drop_duplicates("qid").assign(event_id=lambda d: d.qid.astype(str))
    start = pd.concat([pd.read_parquet(f, columns=["qid", "question_start_date"])
                       for f in glob.glob(f"{RAW}/{name}-*.parquet")]).drop_duplicates("qid")
    raw = raw.merge(start, on="qid")
    if split in STANDALONE:
        return jev_columns(raw).reset_index(drop=True)
    base = pd.read_parquet(BASE)
    base = base[base.split == SPLITS[name]]
    return raw.drop(columns=["split", "answer"]).merge(base, on="event_id").reset_index(drop=True)


def jev_columns(d):
    state = d.apply(state_text, axis=1)
    as_json = [json.dumps({"background": " ".join(b.split()), "resolution_rules": criteria(r)}, ensure_ascii=False)
               for b, r in zip(d.background, d.itertuples())]
    return d.assign(question=d.question_title.str.strip(), category=d.atype, horizon_days=0, state=state,
                    state_price=state, state_context=state, state_json=as_json)


def criteria(r):
    return " ".join(re.sub(r"<[^>]+>", " ", r.resolution_criteria).split())


class Model:
    """gpt-oss-120b in vLLM: chat prompts with a chosen current date and reasoning effort, final-channel text."""

    def __init__(self):
        self.tok = AutoTokenizer.from_pretrained(MODEL)
        self.llm = LLM(MODEL, max_model_len=8192, gpu_memory_utilization=0.9, seed=0)
        self.today = f"Current date: {date.today():%Y-%m-%d}"

    def prompt(self, text, effort, start=None):
        p = self.tok.apply_chat_template([{"role": "user", "content": text}], tokenize=False,
                                         add_generation_prompt=True, reasoning_effort=effort)
        assert self.today in p
        return p.replace(self.today, f"Current date: {start}") if start else p

    def ask(self, prompts, max_tokens, temperature=0.0):
        outs = self.llm.generate(prompts, SamplingParams(temperature=temperature, max_tokens=max_tokens, seed=0))
        return [o.outputs[0].text.split("assistantfinal")[-1] for o in outs]

    def letters(self, prompts, ks):
        """Probability per option (ks: options per prompt) from the next-token distribution over the letters, the
        final channel forced."""
        outs = self.llm.generate([p + "<|channel|>final<|message|>" for p in prompts],
                                 SamplingParams(temperature=0.0, max_tokens=1, logprobs=20))
        res = []
        for o, k in zip(outs, ks):
            p = np.zeros(k)
            for v in o.outputs[0].logprobs[0].values():
                t = v.decoded_token.strip()
                if len(t) == 1 and t in LETTERS[:k]:
                    p[LETTERS.index(t)] += np.exp(v.logprob)
            res.append(p / p.sum() if p.sum() > 0 else np.full(k, 1 / k))
        return res

    def same(self, triples):
        """For each (question, ground truth, response), True if the authors' judge prompt says they match."""
        outs = self.ask([self.prompt(judge_prompt(*t), "low") for t in triples], 1024)
        return [bool(re.search(r"<answer>\s*1\s*</answer>", o)) for o in outs]


def gen_prompt(r):
    return f"""You are writing the answer options of a multiple-choice forecasting question.

Question: {r.question_title}
Background: {" ".join(r.background.split())}
Resolution criteria: {criteria(r)}
Expected answer type: {r.answer_type}

As of today, list {N_GENERATED} distinct answers that a well-informed forecaster would seriously consider, the most likely first. Each must be a specific, realistic possibility of the expected answer type and in the accepted answer format, consistent with the background. Use only real, existing people, organisations, places and things that you know of; never invent a name. Give each answer alone, without descriptions, titles or explanations. Put the answers one per line inside <candidates> </candidates> tags."""


def fit_prompt(r, cands):
    listed = "".join(f"{i + 1}. {c}\n" for i, c in enumerate(cands))
    return f"""Question: {r.question_title}
Resolution criteria: {criteria(r)}
Expected answer type: {r.answer_type}

Candidate answers:
{listed}
Judge every candidate separately, only on its kind and form. Answer "no" only if the candidate is the wrong kind of answer for what is asked (for example a person when a country is asked, a baseball team for a basketball question, a city when a date is asked) or is not in the accepted answer format of the resolution criteria (for example it adds a description to a name). Do not judge whether it is likely, current, true or still holds the role: a candidate of the right kind and form fits even if you think it will not be the answer.
Inside <fit> </fit> tags, write one line per candidate, "N: yes" or "N: no"."""


def style_prompt(question, options):
    listed = "".join(f"{i + 1}. {o}\n" for i, o in enumerate(options))
    return f"""These are the answer options of a multiple-choice question.

Question: {question}
Options:
{listed}
Rewrite the options so that they share one consistent style: give each in the plainest common form of its name, with the same naming conventions and level of detail, and drop qualifiers that only some options carry (a suffix, title, legal form, article or descriptive label); never add a qualifier or label to the options. Every option must still refer to exactly the same thing as before; do not merge, replace, reorder or correct any option. Put the {len(options)} rewritten options, in the same order, one per line inside <options> </options> tags."""


def probe_prompt(options):
    listed = "".join(f"{LETTERS[i]}. {o}\n" for i, o in enumerate(options))
    return (f"Below are {len(options)} candidate answers to a forecasting question you cannot see. Exactly one of "
            f"them is the true answer.\n\n{listed}\nWhich one is the true answer? Reply with its letter only.")


def tagged_lines(text, tag):
    m = list(re.finditer(rf"<{tag}>(.*?)</{tag}>", text, re.DOTALL))
    if not m:
        return None
    lines = [re.sub(r"^\s*(?:\d+[.)]|[-*•])\s*", "", l).strip() for l in m[-1].group(1).splitlines()]
    return [l for l in lines if l]


def parse_fit(text, k):
    m = list(re.finditer(r"<fit>(.*?)</fit>", text, re.DOTALL))
    if not m:
        return None
    verdict = {int(i) - 1: v.lower() == "yes"
               for i, v in re.findall(r"^\s*\W*(\d+)\W*?\s*[:.)-]?\s*\W*(yes|no)\b", m[-1].group(1), re.I | re.M)}
    return sorted(i for i, ok in verdict.items() if ok and i < k) if len(verdict) == k else None


def overlaps(a, b):
    a, b = norm(a), norm(b)
    return a == b or (min(len(a), len(b)) > 2 and (a in b or b in a))


def real_answers(d, split):
    """Rule 1: for each question, the answers of the most similar other questions of its answer type, then those
    of the most similar questions of any type (rule 2 drops the wrong kinds), MAX_CANDIDATES in all."""
    train = load("train").drop_duplicates("qid")
    pool = train if split == "train" else pd.concat([train, load(RAW_NAME[split])]).drop_duplicates("qid")
    vec = TfidfVectorizer(stop_words="english", sublinear_tf=True, min_df=2).fit(pool.question_title)
    same = distractors(d, pool, vec, k=MAX_CANDIDATES)
    anytype = distractors(d.assign(atype=""), pool.assign(atype=""), vec, k=MAX_CANDIDATES)
    out = []
    for s, a in zip(same, anytype):
        cs = list(s) if isinstance(s, list) else []
        seen = set(map(norm, cs))  # exact repeats; rule 3 drops overlapping ones among those that fit
        out.append((cs + [c for c in a if norm(c) not in seen])[:MAX_CANDIDATES])
    return out


def candidates(m, d, split):
    """Rules 1-2, cached per split: each question's pool is fit-checked N_CANDIDATES at a time, most similar first,
    until N_DISTRACTORS + 2 candidates fit or the pool runs out; on evaluation splits the generated candidates
    follow (candidates from index n_real on). fit holds the indices of the checked candidates that fit (an
    unparsed verdict fits none of its batch)."""
    if os.path.exists(cand_path(split)):
        return pd.read_parquet(cand_path(split))
    pools = real_answers(d, split)
    cands, fit = [[] for _ in pools], [[] for _ in pools]
    for start in range(0, MAX_CANDIDATES, N_CANDIDATES):
        todo = [i for i, p in enumerate(pools) if len(fit[i]) < N_DISTRACTORS + 2 and start < len(p)]
        if not todo:
            break
        batch = [pools[i][start:start + N_CANDIDATES] for i in todo]
        texts = m.ask([m.prompt(fit_prompt(d.iloc[i], b), "medium", d.question_start_date[i])
                       for i, b in zip(todo, batch)], 4096)
        for i, b, t in zip(todo, batch, texts):
            fit[i] += [len(cands[i]) + j for j in parse_fit(t, len(b)) or []]
            cands[i] += b
        print(f"rule 2 from candidate {start}: {len(todo)} questions checked", flush=True)
    n_real = [len(c) for c in cands]
    if split in FALLBACK:
        short = [i for i in range(len(d)) if len(fit[i]) < N_DISTRACTORS + 2]
        gen = [tagged_lines(t, "candidates") or [] for t in m.ask(
            [m.prompt(gen_prompt(d.iloc[i]), "medium", d.question_start_date[i]) for i in short], 6144, 1.0)]
        texts = m.ask([m.prompt(fit_prompt(d.iloc[i], g), "medium", d.question_start_date[i]) if g else "x"
                       for i, g in zip(short, gen)], 4096)
        for i, g, t in zip(short, gen, texts):
            fit[i] += [len(cands[i]) + j for j in (parse_fit(t, len(g)) if g else None) or []]
            cands[i] += g
        print(f"generated candidates for {len(short)} questions", flush=True)
    d = d.assign(candidates=cands, fit=fit, n_real=n_real)
    d.to_parquet(cand_path(split))
    return d


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", choices=list(RAW_NAME), required=True)
    split = ap.parse_args().split
    m = Model()
    d = candidates(m, questions(split), split)

    # rule 2 (misfits) and rule 3 (restatements of the truth, repeats)
    cands = [[cs[i] for i in f] for cs, f in zip(d.candidates, d.fit)]
    cands = [[c for c in cs if not overlaps(c, a)] for cs, a in zip(cands, d.answer)]
    triples = [(q, a, c) for q, a, cs in zip(d.question_title, d.answer, cands) for c in cs]
    same = iter(m.same(triples))
    cands = [[c for c in cs if not next(same)] for cs in cands]
    survivors = []
    for cs in cands:
        out = []
        for c in cs:
            if not any(overlaps(c, o) for o in out):
                out.append(c)
        survivors.append(out)

    # rule 4: the option set, rewritten into one style
    keep = [i for i, sv in enumerate(survivors) if len(sv) >= (1 if split in FALLBACK else N_DISTRACTORS)]
    sets, n_gen = {}, {}
    for k, i in enumerate(keep):
        r = d.iloc[i]
        n = min(N_DISTRACTORS, len(survivors[i]))
        opts = [survivors[i][j] for j in np.random.default_rng(int(r.qid)).permutation(n)]
        n_gen[i] = sum(o in set(r.candidates[r.n_real:]) for o in opts)
        y = k % (N_DISTRACTORS + 1) % (n + 1)
        sets[i] = (opts[:y] + [str(r.answer)] + opts[y:], y)
    styled = m.ask([m.prompt(style_prompt(d.question_title[i], sets[i][0]), "low") for i in keep], 2048)
    styled = [tagged_lines(t, "options") for t in styled]
    check = [(d.question_title[i], sets[i][0][sets[i][1]], st[sets[i][1]])
             for i, st in zip(keep, styled) if st and len(st) == len(sets[i][0])]
    ok = iter(m.same(check))
    n_styled = 0
    for i, st in zip(keep, styled):
        opts, y = sets[i]
        if not st or len(st) != len(opts):
            continue
        if next(ok) and not any(overlaps(st[j], st[y]) for j in range(len(st)) if j != y):
            sets[i] = (st, y)
            n_styled += 1

    # rule 5: option-only probe, a check of the whole set
    probs = m.letters([m.prompt(probe_prompt(sets[i][0]), "low") for i in keep], [len(sets[i][0]) for i in keep])
    rows = []
    for i, p in zip(keep, probs):
        opts, y = sets[i]
        r = d.iloc[i]
        row = {c: r[c] for c in d.columns if c != "fit"}
        rows.append(row | {"options": opts, "y_index": y, "n_options": len(opts), "probe_p_truth": float(p[y]),
                           "probe_top": int(np.argmax(p)) == y, "crowd": [1 / len(opts)] * len(opts),
                           "n_generated": n_gen[i]})
    name = SPLITS[RAW_NAME[split]]
    o = pd.DataFrame(rows).assign(split=name)
    path = out_path(split)
    if os.path.exists(path) and split not in STANDALONE:  # one file holds train, val and futureSim2026Q2
        old = pd.read_parquet(path)
        o = pd.concat([old[old.split != name], o], ignore_index=True)
    o.to_parquet(path)
    s = o[o.split == name]
    n_misfit = sum(len(c) - len(f) for c, f in zip(d.candidates, d.fit))
    print(f"{split}: {len(d)} questions, {len(s)} kept | candidates {sum(map(len, d.candidates))}: misfit dropped "
          f"{n_misfit}, restatements dropped {len(triples) - sum(map(len, cands))} | sets with generated distractors "
          f"{(s.n_generated > 0).sum()} | restyled "
          f"{n_styled}/{len(keep)} sets | option-only probe: accuracy {s.probe_top.mean():.3f} (chance "
          f"{np.mean(1 / s.n_options):.2f}), mean p(truth) "
          f"{s.probe_p_truth.mean():.3f} | truth position {np.bincount(s.y_index, minlength=N_DISTRACTORS + 1).tolist()} | options per set "
          f"{s.n_options.value_counts().sort_index().to_dict()}")
    for r in s.sample(min(8, len(s)), random_state=1).itertuples():
        print(r.question_title, "|", list(r.options), "| true:", r.options[r.y_index])


if __name__ == "__main__":
    main()
